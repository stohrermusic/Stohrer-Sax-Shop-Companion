"""Gate: no new silently swallowed exception (2026-11-09, pre-3.0 housekeeping).

An audit of the 208 `except ...: pass` handlers in the root modules put each in a class:
(a) deliberate and harmless, kept silent (widget teardown, a Tk call on a window that may be
gone, a cosmetic call, an optional import); (b) worth knowing about, now logged; (c) a hidden
bug (none found). The calibration dialog that shipped broken from v2.7 to v2.85 sat behind one
of these handlers, so the number must not grow unnoticed. This scan fails on:

  * a bare `except:` anywhere in a root module (there were none; keep it so);
  * an `except Exception` / `except BaseException` (alone or in a tuple) whose whole body is
    `pass` (or `...`) that is not in ALLOWED below, by file and enclosing function, with the
    exact count: a new one in an allowed function fails too, and so does one that was removed
    without this list being updated, so the list always says what is there.

A handler that catches a narrower type and stays silent (`except tk.TclError: pass`) is class a
by construction and is not counted. To add a deliberate silent `except Exception: pass`, add its
(file, function) here with a reason in the audit table (CLAUDE-architecture.md, "Error
Logging"). To make a swallowed failure visible, log it with the module's logger and leave the
control flow alone: that is what the 47 class-b sites now do.

Also pins the once-then-count pattern of the per-frame loops that log: a handler on a timer must
never log per tick.
"""
