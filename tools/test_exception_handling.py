SWALLOWING = {"Exception", "BaseException"}

results = []


def check(name, fn):
    try:
        ok = fn()
        if ok is False:
            raise AssertionError("returned False")
        print(f"  PASS  {name}")
        results.append(True)
    except Exception as e:  # noqa: BLE001
        print(f"  FAIL  {name}: {e}")
        results.append(False)


def _root_modules():
    return sorted(f for f in os.listdir(ROOT) if f.endswith(".py") and os.path.isfile(os.path.join(ROOT, f)))


def _body_is_pass(handler):
    return all(isinstance(s, ast.Pass)
               or (isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant) and s.value.value is Ellipsis)
               for s in handler.body)


def _caught_names(handler):
    t = handler.type
    if t is None:
        return None
    elts = t.elts if isinstance(t, ast.Tuple) else [t]
    return {ast.unparse(e) for e in elts}


def scan(path):
    """Every handler of interest in one module: (function, line, kind) with kind 'bare' or
    'swallow' (a silent except Exception/BaseException)."""
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src, filename=path)
    found = []

    class V(ast.NodeVisitor):
        def __init__(self):
            self.stack = []

        def visit_FunctionDef(self, node):
            self.stack.append(node.name)
            self.generic_visit(node)
            self.stack.pop()
        visit_AsyncFunctionDef = visit_FunctionDef

        def visit_ClassDef(self, node):
            self.stack.append(node.name)
            self.generic_visit(node)
            self.stack.pop()

        def visit_Try(self, node):
            where = ".".join(self.stack) or "<module>"
            for h in node.handlers:
                names = _caught_names(h)
                if names is None:
                    found.append((where, h.lineno, "bare"))
                elif _body_is_pass(h) and names & SWALLOWING:
                    found.append((where, h.lineno, "swallow"))
            self.generic_visit(node)
        visit_TryStar = visit_Try

    V().visit(tree)
    return found


def no_bare_except():
    bare = [(f, w, ln) for f in _root_modules() for (w, ln, k) in scan(os.path.join(ROOT, f)) if k == "bare"]
    assert not bare, "bare `except:` in a root module (catch a type, or Exception with a log line):\n    " + \
        "\n    ".join(f"{f}:{ln} in {w}" for f, w, ln in bare)


def silent_except_exception_only_where_allowed():
    counts = {}
    lines = {}
    for f in _root_modules():
        for w, ln, k in scan(os.path.join(ROOT, f)):
            if k == "swallow":
                counts[(f, w)] = counts.get((f, w), 0) + 1
                lines.setdefault((f, w), []).append(ln)
    new = {k: v for k, v in counts.items() if k not in ALLOWED}
    grown = {k: (v, ALLOWED[k]) for k, v in counts.items() if k in ALLOWED and v > ALLOWED[k]}
    gone = {k: (counts.get(k, 0), v) for k, v in ALLOWED.items() if counts.get(k, 0) < v}
    msg = []
    if new:
        msg.append("new silent `except Exception: pass` (log it, narrow it, or add it to ALLOWED with a reason):\n    " +
                   "\n    ".join(f"{f}:{lines[(f, w)]} in {w}" for (f, w) in sorted(new)))
    if grown:
        msg.append("more silent handlers than ALLOWED in:\n    " +
                   "\n    ".join(f"{f} {w}: {v} (allowed {a}) at {lines[(f, w)]}" for (f, w), (v, a) in sorted(grown.items())))
    if gone:
        msg.append("fewer silent handlers than ALLOWED (update the list so it says what is there):\n    " +
                   "\n    ".join(f"{f} {w}: {v} (allowed {a})" for (f, w), (v, a) in sorted(gone.items())))
    assert not msg, "\n".join(msg)
    total = sum(counts.values())
    print(f"    ({total} deliberate silent handlers in {len(counts)} functions, all listed)")


def the_allow_list_is_well_formed():
    assert ALLOWED, "the allow-list is empty: the audit's class-a sites must be listed"
    for (f, w), n in ALLOWED.items():
        assert f in _root_modules(), f"{f} is not a root module"
        assert isinstance(n, int) and n > 0, (f, w, n)


