def thirtytwonds_to_mm(n):
    """Convert 32nds of an inch to mm, rounded to 1 decimal."""
    return round(n * 25.4 / 32, 1)

def build_pad_string(size_qty_pairs):
    lines = []
    for size_32, qty in size_qty_pairs:
        mm = thirtytwonds_to_mm(size_32)
        lines.append(f"{mm} x {qty}")
    return "\n".join(lines)

